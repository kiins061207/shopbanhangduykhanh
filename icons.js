/* Trả về <svg> của icon */
function icon(ten) {
    var d = ICONS[ten];
    if (!d) return "";
    return '<svg viewBox="0 0 24 24" aria-hidden="true" focusable="false">' + d + '</svg>';
}

/* Trả về <span> bọc icon (dùng khi ghép chuỗi HTML trong JS) */
function ic(ten) {
    return '<span class="ic">' + icon(ten) + '</span>';
}

/* Thay mọi <span data-icon="..."> trong trang bằng icon thật */
function veIcon(goc) {
    var ds = (goc || document).querySelectorAll("[data-icon]");
    for (var i = 0; i < ds.length; i++) {
        ds[i].className = (ds[i].className + " ic").trim();
        ds[i].innerHTML = icon(ds[i].getAttribute("data-icon"));
        ds[i].removeAttribute("data-icon");
    }
}
